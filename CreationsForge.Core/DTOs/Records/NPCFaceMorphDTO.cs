namespace CreationsForge.Core.DTOs.Records;

/// <summary>
/// Represents Skyrim NPC face morph sliders exported under Spriggit's <c>FaceMorph</c> object.
/// </summary>
public class NPCFaceMorphDTO
{
    /// <summary>
    /// Gets or sets the nose long-vs-short slider.
    /// </summary>
    public double? NoseLongVsShort { get; set; }

    /// <summary>
    /// Gets or sets the nose up-vs-down slider.
    /// </summary>
    public double? NoseUpVsDown { get; set; }

    /// <summary>
    /// Gets or sets the jaw up-vs-down slider.
    /// </summary>
    public double? JawUpVsDown { get; set; }

    /// <summary>
    /// Gets or sets the jaw narrow-vs-wide slider.
    /// </summary>
    public double? JawNarrowVsWide { get; set; }

    /// <summary>
    /// Gets or sets the jaw forward-vs-back slider.
    /// </summary>
    public double? JawForwardVsBack { get; set; }

    /// <summary>
    /// Gets or sets the cheeks up-vs-down slider.
    /// </summary>
    public double? CheeksUpVsDown { get; set; }

    /// <summary>
    /// Gets or sets the cheeks forward-vs-back slider.
    /// </summary>
    public double? CheeksForwardVsBack { get; set; }

    /// <summary>
    /// Gets or sets the eyes up-vs-down slider.
    /// </summary>
    public double? EyesUpVsDown { get; set; }

    /// <summary>
    /// Gets or sets the eyes in-vs-out slider.
    /// </summary>
    public double? EyesInVsOut { get; set; }

    /// <summary>
    /// Gets or sets the brows up-vs-down slider.
    /// </summary>
    public double? BrowsUpVsDown { get; set; }

    /// <summary>
    /// Gets or sets the brows in-vs-out slider.
    /// </summary>
    public double? BrowsInVsOut { get; set; }

    /// <summary>
    /// Gets or sets the brows forward-vs-back slider.
    /// </summary>
    public double? BrowsForwardVsBack { get; set; }

    /// <summary>
    /// Gets or sets the lips up-vs-down slider.
    /// </summary>
    public double? LipsUpVsDown { get; set; }

    /// <summary>
    /// Gets or sets the lips in-vs-out slider.
    /// </summary>
    public double? LipsInVsOut { get; set; }

    /// <summary>
    /// Gets or sets the chin narrow-vs-wide slider.
    /// </summary>
    public double? ChinNarrowVsWide { get; set; }

    /// <summary>
    /// Gets or sets the chin up-vs-down slider.
    /// </summary>
    public double? ChinUpVsDown { get; set; }

    /// <summary>
    /// Gets or sets the chin underbite-vs-overbite slider.
    /// </summary>
    public double? ChinUnderbiteVsOverbite { get; set; }

    /// <summary>
    /// Gets or sets the eyes forward-vs-back slider.
    /// </summary>
    public double? EyesForwardVsBack { get; set; }

    /// <summary>
    /// Gets or sets the unknown face morph value.
    /// </summary>
    public double? Unknown { get; set; }
}
